const IMAGE_INPUT_PREFIXES = ["claude-", "gemini-", "gpt-", "default"];

function cursorModel(id: string, name: string, contextWindow: number, effort: ModelThinkingLevel | false): Model<"cursor-agent"> {
	const model: Model<"cursor-agent"> = {
		id,
		name: `${name} (Cursor)`,
		api: "cursor-agent",
		provider: "cursor",
		baseUrl: "https://api2.cursor.sh",
		reasoning: effort !== false,
		input: IMAGE_INPUT_PREFIXES.some((prefix) => id.startsWith(prefix)) ? ["text", "image"] : ["text"],
		contextWindow,
		maxTokens: 64_000,
		cost: { input: 0, output: 0, cacheRead: 0, cacheWrite: 0 },
	};
	if (effort !== false) {
		model.thinkingLevelMap = Object.fromEntries(LEVELS.map((level) => [level, level === effort ? effort : null]));
	}
	return model;
}

export function cursorModels(): Model<"cursor-agent">[] {
	return MODEL_ROWS.map(([id, name, contextWindow, effort]) => cursorModel(id, name, contextWindow, effort));
}
