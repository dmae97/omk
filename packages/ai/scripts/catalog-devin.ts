function flatModel(uid: string, name: string, contextWindow: number, maxTokens: number, effort: ModelThinkingLevel | false): Model<"devin-agent"> {
	const model: Model<"devin-agent"> = {
		id: uid,
		name: `${name} (Devin CLI)`,
		api: "devin-agent",
		provider: "devin",
		baseUrl: "https://server.codeium.com",
		reasoning: effort !== false,
		input: ["text"],
		contextWindow,
		maxTokens,
		cost: { input: 0, output: 0, cacheRead: 0, cacheWrite: 0 },
	};
	if (effort !== false) {
		model.thinkingLevelMap = Object.fromEntries(LEVELS.map((level) => [level, level === effort ? effort : null]));
	}
	return model;
}

/** Logical `swe-2` plus one model per wire UID in the observed account catalog. */
export function devinModels(): Model<"devin-agent">[] {
	return [swe2LogicalModel(), ...FLAT_MODELS.map(([uid, name, cw, mt, effort]) => flatModel(uid, name, cw, mt, effort))];
}
